export type StateNameKey = keyof typeof STATE_NAMES;

/**
 * Returns a copy of a static translated object name.
 *
 * @param key The translation key.
 */
export function translatedName(key: TranslationKey | StateNameKey): TranslatedName {
	const value = (OBJECT_NAMES[key as TranslationKey] || STATE_NAMES[key as StateNameKey]) as TranslatedName;
	return { ...value };
}

/**
 * Returns a translated fallback lesson name with its slot appended.
 *
 * @param slot The lesson slot.
 */
export function translatedLessonFallback(slot: string): TranslatedName {
	const result = translatedName("lessonFallback");
	for (const language of SUPPORTED_LANGUAGES) {
		result[language] = `${result[language]} ${slot}`;
	}
	return result;
}

