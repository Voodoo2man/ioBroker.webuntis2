export function translatedTimetableGroup(group: string): TranslatedName {
	return { ...(TIMETABLE_GROUP_NAMES[group] || { en: `Timetable ${group}` }) };
}

/**
 * Returns the translated name for a weekday.
 *
 * @param day The weekday key.
 */
export function translatedWeekday(day: string): TranslatedName {
	return { ...(WEEKDAY_NAMES[day] || { en: day || "Day" }) };
}

/**
 * Checks whether an existing name is the known legacy default.
 *
 * @param current The current object name.
 * @param legacy The legacy default name.
 */
export function needsNameMigration(current: ioBroker.StringOrTranslated | undefined, legacy: string): boolean {
	return (
		(typeof current === "string" && current === legacy) ||
		(typeof current === "object" && current !== null && current.en === legacy)
	);
}

/**
 * Checks whether a lesson channel name has the format generated by the adapter.
 *
 * @param name The current object name.
 */
export function isGeneratedLessonName(name: ioBroker.StringOrTranslated | undefined): boolean {
	return (
		typeof name === "string" &&
		(/^(?:\d{1,2}:\d{2})(?:–\d{1,2}:\d{2})?(?: · .+)?$/.test(name) || /^Lesson \d{2}$/.test(name))
	);
}

/**
 * Checks whether a dynamic object name may be updated by the adapter.
 *
 * @param current The current object name.
 * @param generatedName The last name generated by the adapter, if known.
 */
export function shouldMigrateDynamicName(
	current: ioBroker.StringOrTranslated | undefined,
	generatedName?: string,
): boolean {
	return typeof generatedName === "string" ? generatedName === current : isGeneratedLessonName(current);
}

/**
 * Checks whether an object value differs from its desired value.
 *
 * @param current The value currently stored on the object.
 * @param desired The value required by the adapter.
 */
export function hasObjectValueChanged(current: unknown, desired: unknown): boolean {
	return JSON.stringify(current) !== JSON.stringify(desired);
}

const LEGACY_STATE_NAMES: Record<string, StateNameKey> = Object.fromEntries(
	Object.entries(STATE_NAMES).map(([key, value]) => [value.en, key]),
) as Record<string, StateNameKey>;

/**
 * Returns a translated state name, or the original name when unknown.
 *
 * @param name The legacy English state name.
 */
export function translatedStateName(name: string): TranslatedName {
	const key = LEGACY_STATE_NAMES[name];
	return key ? translatedName(key) : { en: name };
}
